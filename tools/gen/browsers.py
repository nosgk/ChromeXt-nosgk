#!/usr/bin/env python3
"""Generate the browser catalog from browser/browsers.json.

Generated files:
  app/src/main/kotlin/org/matrix/chromext/browser/BrowserCatalog.kt
  app/src/main/res/values/arrays.xml
  the <queries> block in app/src/main/AndroidManifest.xml

Run with --check to verify that the committed files are current.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "browser" / "browsers.json"
CATALOG = (
    ROOT / "app" / "src" / "main" / "kotlin" / "org" / "matrix" / "chromext" / "browser" / "BrowserCatalog.kt"
)
ARRAYS = ROOT / "app" / "src" / "main" / "res" / "values" / "arrays.xml"
MANIFEST = ROOT / "app" / "src" / "main" / "AndroidManifest.xml"

BEGIN = "    <!-- BEGIN GENERATED BROWSERS -->"
END = "    <!-- END GENERATED BROWSERS -->"


def load() -> tuple[list[str], list[str]]:
    data = json.loads(CONFIG.read_text(encoding="utf-8"))
    chromium = data["chromium"]
    webview = data["webview"]
    for name in chromium + webview:
        if not re.fullmatch(r"[a-z0-9_]+(\.[a-z0-9_]+)+", name):
            raise SystemExit(f"invalid package name: {name}")
    if len(set(chromium + webview)) != len(chromium) + len(webview):
        raise SystemExit("duplicate package name in browser/browsers.json")
    return chromium, webview


def kotlin_array(name: str, items: list[str]) -> str:
    lines = [f"  val {name} =", "      arrayOf("]
    lines.extend(f'          "{item}",' for item in items)
    lines.append("      )")
    return "\n".join(lines)


def render_catalog(chromium: list[str], webview: list[str]) -> str:
    scope = sorted(chromium + webview)
    return (
        "package org.matrix.chromext.browser\n"
        "\n"
        "// Generated by tools/gen/browsers.py from browser/browsers.json. Do not edit.\n"
        "object BrowserCatalog {\n"
        f"{kotlin_array('supportedPackages', chromium)}\n"
        "\n"
        "  val webViewPackages =\n"
        "      setOf(\n"
        + "\n".join(f'          "{item}",' for item in webview)
        + "\n"
        "      )\n"
        "\n"
        f"{kotlin_array('xposedScope', scope)}\n"
        "\n"
        f"{kotlin_array('packageQueries', scope)}\n"
        "\n"
        "  fun isWebView(packageName: String): Boolean = packageName in webViewPackages\n"
        "}\n"
    )


def render_arrays(chromium: list[str], webview: list[str]) -> str:
    scope = sorted(chromium + webview)
    items = "\n".join(f"\t\t<item>{item}</item>" for item in scope)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<resources>\n"
        '\t<string-array name="xposedscope">\n'
        f"{items}\n"
        "\t</string-array>\n"
        "</resources>\n"
    )


def render_queries(chromium: list[str], webview: list[str]) -> str:
    scope = sorted(chromium + webview)
    packages = "\n".join(f'        <package android:name="{item}" />' for item in scope)
    return f"{BEGIN}\n    <queries>\n{packages}\n    </queries>\n{END}"


def render_manifest(original: str, chromium: list[str], webview: list[str]) -> str:
    block = render_queries(chromium, webview)
    if BEGIN in original and END in original:
        pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        return pattern.sub(block, original, count=1)
    pattern = re.compile(r"[ \t]*<queries>.*?</queries>", re.S)
    if not pattern.search(original):
        raise SystemExit("AndroidManifest.xml has no <queries> block to replace")
    return pattern.sub(block, original, count=1)


def main() -> int:
    chromium, webview = load()
    outputs = {
        CATALOG: render_catalog(chromium, webview),
        ARRAYS: render_arrays(chromium, webview),
        MANIFEST: render_manifest(MANIFEST.read_text(encoding="utf-8"), chromium, webview),
    }

    if "--check" in sys.argv:
        stale = [path for path, content in outputs.items() if path.read_text(encoding="utf-8") != content]
        for path in stale:
            print(f"stale generated file: {path.relative_to(ROOT)}")
        if stale:
            print("run: python3 tools/gen/browsers.py")
            return 1
        print("browser catalog is current")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
